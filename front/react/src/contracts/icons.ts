const NAMES: ReadonlySet<string> = new Set(ICON_NAMES);
const DIRECTIONAL: ReadonlySet<string> = new Set(DIRECTIONAL_ICONS);

/** ¿Es un nombre de icono conocido? (estrecha el tipo a `IconName`) */
export function isIconName(value: unknown): value is IconName {
  return typeof value === 'string' && NAMES.has(value);
}

/** ¿Se espeja en RTL? Un nombre desconocido no se espeja. */
export function isDirectionalIcon(name: string): boolean {
  return DIRECTIONAL.has(name);
}

/** Nombre kebab de Phosphor de un nombre de icono (el propio nombre si no es un alias). */
export function phosphorNameOf(name: IconName): string {
  return name in ICON_ALIASES ? ICON_ALIASES[name as IconAlias] : name;
}
